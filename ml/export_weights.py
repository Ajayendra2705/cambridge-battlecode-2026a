import argparse

import numpy as np
import torch

from common import OUT, ROOT


def lit(v):
    t = f"{float(v):.9g}"
    return (t if any(ch in t for ch in ".en") else t + ".0") + "f"


def fmt(a):
    return "{" + ", ".join(lit(v) for v in np.asarray(a, np.float32).ravel()) + "}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("bot")
    ap.add_argument("--seeds", default="0")
    ap.add_argument("--prefix", default="model", help="checkpoint name prefix, e.g. model_team")
    ap.add_argument("--team", help="teamId whose embedding the bot plays with (team variant only)")
    ap.add_argument("--gate", action="store_true", help="act only when every model agrees on engage vs stay")
    ap.add_argument("--commit", type=float, default=0.0, help="hysteresis margin in label std units (0 = off)")
    args = ap.parse_args()
    seeds = [int(s) for s in args.seeds.split(",")]
    ckpts = [torch.load(OUT / f"{args.prefix}_s{s}.pt", weights_only=False) for s in seeds]
    ws = [{k: v.cpu().numpy() for k, v in c["state"].items()} for c in ckpts]
    s, w = ckpts[0]["stats"], ws[0]
    n_unit, width = w["phi_x.weight"].shape[1], w["phi_x.weight"].shape[0]
    n_game, hidden, n = ckpts[0].get("n_game", len(ckpts[0]["game_features"])), w["stay.0.weight"].shape[0], len(ws)
    stacked = lambda f: np.stack([f(x) for x in ws])
    arrays = [
        ("FQ_UNIT_MEAN", f"[{n_unit}]", s["unit_mean"]),
        ("FQ_UNIT_STD", f"[{n_unit}]", s["unit_std"]),
        ("FQ_GAME_MEAN", f"[{n_game}]", s["game_mean"]),
        ("FQ_GAME_STD", f"[{n_game}]", s["game_std"]),
        ("FQ_PHI_X", f"[{n}][{n_unit}][{width}]", stacked(lambda x: x["phi_x.weight"].T)),
        ("FQ_PHI_B", f"[{n}][{width}]", stacked(lambda x: x["phi_x.bias"])),
        ("FQ_EMB", f"[{n}][{w['phi_t.weight'].shape[0]}][{width}]", stacked(lambda x: x["phi_t.weight"])),
        ("FQ_ENG1", f"[{n}][{w['engage.0.weight'].shape[1]}][{hidden}]", stacked(lambda x: x["engage.0.weight"].T)),
        ("FQ_ENG1_B", f"[{n}][{hidden}]", stacked(lambda x: x["engage.0.bias"])),
        ("FQ_ENG2", f"[{n}][{hidden}]", stacked(lambda x: x["engage.2.weight"][0])),
        ("FQ_ENG2_B", f"[{n}]", stacked(lambda x: x["engage.2.bias"])),
        ("FQ_STAY1", f"[{n}][{w['stay.0.weight'].shape[1]}][{hidden}]", stacked(lambda x: x["stay.0.weight"].T)),
        ("FQ_STAY1_B", f"[{n}][{hidden}]", stacked(lambda x: x["stay.0.bias"])),
        ("FQ_STAY2", f"[{n}][{hidden}]", stacked(lambda x: x["stay.2.weight"][0])),
        ("FQ_STAY2_B", f"[{n}]", stacked(lambda x: x["stay.2.bias"])),
    ]
    team_dim = w["team.weight"].shape[1] if "team.weight" in w else 0
    if team_dim:
        keys = list(np.load(OUT / "teams.npz")["team_keys"])
        tid = keys.index(args.team) + 1 if args.team in keys else 0
        arrays.append(("FQ_TEAM_EMB", f"[{n}][{team_dim}]", stacked(lambda x: x["team.weight"][tid])))
    else:
        arrays.append(("FQ_TEAM_EMB", f"[{n}][1]", np.zeros((n, 1))))
    lines = [
        f"// Generated by ml/export_weights.py from data/ml/{args.prefix}_s{{{args.seeds}}}.pt. Do not edit.",
        f"// Unit features: {' '.join(ckpts[0]['unit_features'])}. Game features: {' '.join(ckpts[0]['game_features'])}.",
        f"constexpr int FQ_UNIT = {n_unit}, FQ_GAME = {n_game}, FQ_W = {width}, FQ_H = {hidden}, FQ_MODELS = {n};",
        f"constexpr int FQ_TEAM_DIM = {team_dim};",
        f"constexpr bool FQ_GATE = {'true' if args.gate else 'false'};",
        f"constexpr float FQ_COMMIT = {lit(args.commit)};",
    ]
    for name, shape, a in arrays:
        lines.append(f"alignas(16) constexpr float {name}{shape} = {fmt(a)};")
    path = ROOT / "bots" / args.bot / "src" / "fightq_weights.h"
    path.write_text("\n".join(lines) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
