import sys

import numpy as np
import torch

from common import OUT, ROOT


def fmt(a):
    return "{" + ", ".join(f"{v:.9g}f" for v in np.asarray(a, np.float32).ravel()) + "}"


def main():
    bot = sys.argv[1] if len(sys.argv) > 1 else "exp/fq1"
    ckpt = torch.load(OUT / "model.pt", weights_only=False)
    w = {k: v.cpu().numpy() for k, v in ckpt["state"].items()}
    s = ckpt["stats"]
    n_unit, width = w["phi_x.weight"].shape[1], w["phi_x.weight"].shape[0]
    n_game = len(ckpt["game_features"])
    hidden = w["stay.0.weight"].shape[0]
    arrays = [
        ("FQ_UNIT_MEAN", f"[{n_unit}]", s["unit_mean"]),
        ("FQ_UNIT_STD", f"[{n_unit}]", s["unit_std"]),
        ("FQ_GAME_MEAN", f"[{n_game}]", s["game_mean"]),
        ("FQ_GAME_STD", f"[{n_game}]", s["game_std"]),
        ("FQ_PHI_X", f"[{n_unit}][{width}]", w["phi_x.weight"].T),
        ("FQ_PHI_B", f"[{width}]", w["phi_x.bias"]),
        ("FQ_EMB", f"[{w['phi_t.weight'].shape[0]}][{width}]", w["phi_t.weight"]),
        ("FQ_ENG1", f"[{w['engage.0.weight'].shape[1]}][{hidden}]", w["engage.0.weight"].T),
        ("FQ_ENG1_B", f"[{hidden}]", w["engage.0.bias"]),
        ("FQ_ENG2", f"[{hidden}]", w["engage.2.weight"][0]),
        ("FQ_STAY1", f"[{w['stay.0.weight'].shape[1]}][{hidden}]", w["stay.0.weight"].T),
        ("FQ_STAY1_B", f"[{hidden}]", w["stay.0.bias"]),
        ("FQ_STAY2", f"[{hidden}]", w["stay.2.weight"][0]),
    ]
    lines = [
        "// Generated by ml/export_weights.py from data/ml/model.pt. Do not edit.",
        f"// Unit features: {' '.join(ckpt['unit_features'])}. Game features: {' '.join(ckpt['game_features'])}.",
        f"constexpr int FQ_UNIT = {n_unit}, FQ_GAME = {n_game}, FQ_W = {width}, FQ_H = {hidden};",
    ]
    for name, shape, a in arrays:
        lines.append(f"alignas(16) constexpr float {name}{shape} = {fmt(a)};")
    lines.append(f"constexpr float FQ_ENG2_B = {float(w['engage.2.bias'][0]):.9g}f, FQ_STAY2_B = {float(w['stay.2.bias'][0]):.9g}f;")
    path = ROOT / "bots" / bot / "src" / "fightq_weights.h"
    path.write_text("\n".join(lines) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
