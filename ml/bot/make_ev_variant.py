"""Expected-value fight rule (eg5/eg6): python ml/bot/make_ev_variant.py BASE NAME LABEL (LABEL = win or prey_dies).

Replaces `rich` with: engage when P(win) * (prey bag + eg_predict(prey)) > (1 - P(win)) * my bag, where P(win) is the
logistic fit from ml/simcal.py (data/ml/simcal_LABEL.npz) on the fight sim's outputs. Writes the fit into ev_weights.h.
"""
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
ML = Path(__file__).resolve().parents[1]
DATA = Path("/home/ming/work/pytorch/Cambridge-Battlecode-2026-Autumn/data/ml")


def weights(label):
    z = np.load(DATA / f"simcal_{label}.npz")
    f = lambda a: ", ".join(f"{v:.8g}f" for v in np.asarray(a, np.float64).ravel())
    return (f"// Generated by ml/bot/make_ev_variant.py from data/ml/simcal_{label}.npz. Inputs: {', '.join(z['cols'])}\n"
            "#pragma once\n"
            f"constexpr float EV_MEAN[11] = {{{f(z['mean'])}}};\nconstexpr float EV_SCALE[11] = {{{f(z['scale'])}}};\n"
            f"constexpr float EV_COEF[11] = {{{f(z['coef'])}}};\nconstexpr float EV_B = {float(z['intercept'][0]):.8g}f;\n")


PATCHES = [
    ("bot.cpp", '#include "knowledge.h"\n', '#include "knowledge.h"\n#include "eg.h"\n#include "ev_weights.h"\n'),
    ("snapshot.h", "    std::uint32_t gems;\n", "    std::uint32_t gems;\n    std::uint32_t bag = 0;\n"),
    ("knowledge.h", "        snap.type = k.type;\n",
     "        snap.type = k.type;\n        try {\n            snap.bag = k.ch.gem_count();\n        } catch (const cambc::error&) {\n        }\n"),
    ("bot.cpp", "    bool winning = false, sim_me_dies = false;\n",
     "    bool winning = false, sim_me_dies = false;\n    float ev_x[11] = {};\n"),
    ("bot.cpp", "        sim_me_dies = res.unit0_dead;\n",
     "        sim_me_dies = res.unit0_dead;\n"
     "        ev_x[0] = static_cast<float>(res.dead[0]), ev_x[1] = static_cast<float>(res.dead[1]);\n"
     "        ev_x[2] = res.hp_frac[0], ev_x[3] = res.hp_frac[1];\n"),
    ("bot.cpp", "    const bool rich = prey && prey->gems >= 30 && ally_power >= enemy_power * 0.5f && S.hp > S.max_hp * 0.5f && !sim_me_dies;\n",
     "    // Expected-value rule (ml/simcal.py, ml/eg_*): P(win) from the sim's outputs, stakes from bags and predicted enemy gain.\n"
     "    bool rich = false;\n"
     "    if (prey && cambc::fuel_remaining() > 20000) {\n"
     "        ev_x[4] = std::log(std::clamp(ally_power / std::max(1.0f, enemy_power), 1e-3f, 1e3f));\n"
     "        ev_x[5] = static_cast<float>(ally_count), ev_x[6] = static_cast<float>(enemy_count);\n"
     "        ev_x[7] = S.hp / std::max(1.0f, S.max_hp), ev_x[8] = prey->hp / std::max(1.0f, prey->max_hp);\n"
     "        ev_x[9] = static_cast<float>(me.gem_count()), ev_x[10] = static_cast<float>(prey->gems);\n"
     "        float z = EV_B;\n"
     "        for (int i = 0; i < 11; ++i) z += EV_COEF[i] * (ev_x[i] - EV_MEAN[i]) / EV_SCALE[i];\n"
     "        const float pw = 1.0f / (1.0f + std::exp(-z));\n"
     "        rich = pw * (static_cast<float>(prey->gems) + eg_predict(*prey)) > (1.0f - pw) * static_cast<float>(me.gem_count());\n"
     "    }\n"),
]


def main():
    base, name, label = sys.argv[1], sys.argv[2], sys.argv[3]
    if (ROOT / "bots" / name).exists():
        sys.exit(f"bots/{name} exists: delete it first")
    subprocess.run([sys.executable, "-I", "tools/variant/mkvar.py", base, name, *[x for p in PATCHES for x in p]], cwd=ROOT, check=True)
    src = ROOT / "bots" / name / "src"
    for f in ["eg.h", "eg_weights.h"]:
        shutil.copy(ML / "bot" / f, src / f)
    (src / "ev_weights.h").write_text(weights(label))
    print(f"made bots/{name} (ev, {label}); build with: cambc build {name} --release")


if __name__ == "__main__":
    main()
