import sys

import numpy as np
import torch

from common import OUT, ROOT
from export_weights import fmt, lit


def main():
    bot = sys.argv[1]
    name = sys.argv[2] if len(sys.argv) > 2 else "rf_model_s0"
    ckpt = torch.load(OUT / f"{name}.pt", weights_only=False)
    shared = ckpt.get("small", False)
    w = {k: v.cpu().numpy() for k, v in ckpt["state"].items()}
    s = ckpt["stats"]
    width, n_unit = w["unit_x.weight"].shape
    n_mem = w["mem_x.weight"].shape[1]
    hidden, n_in = w["head.0.weight" if shared else "head_e.0.weight"].shape
    n_game = n_in - 4 * width
    arrays = [
        ("RF_UNIT_MEAN", f"[{n_unit}]", s["unit"][0]), ("RF_UNIT_STD", f"[{n_unit}]", s["unit"][1]),
        ("RF_MEM_MEAN", f"[{n_mem}]", s["mem"][0]), ("RF_MEM_STD", f"[{n_mem}]", s["mem"][1]),
        ("RF_GAME_MEAN", f"[{n_game}]", s["game"][0]), ("RF_GAME_STD", f"[{n_game}]", s["game"][1]),
        ("RF_UNIT_X", f"[{n_unit}][{width}]", w["unit_x.weight"].T), ("RF_UNIT_B", f"[{width}]", w["unit_x.bias"]),
        ("RF_UNIT_EMB", f"[{w['unit_t.weight'].shape[0]}][{width}]", w["unit_t.weight"]),
        ("RF_MEM_X", f"[{n_mem}][{width}]", w["mem_x.weight"].T), ("RF_MEM_B", f"[{width}]", w["mem_x.bias"]),
        ("RF_MEM_EMB", f"[{w['mem_t.weight'].shape[0]}][{width}]", w["mem_t.weight"]),
    ]
    zeros = lambda *shape: np.zeros(shape, np.float32)
    if shared:
        arrays += [("RF_S1", f"[{n_in}][{hidden}]", w["head.0.weight"].T), ("RF_S1_B", f"[{hidden}]", w["head.0.bias"]),
                   ("RF_S2", f"[2][{hidden}]", w["head.2.weight"]), ("RF_S2_B", "[2]", w["head.2.bias"])]
        for tag in "EA":
            arrays += [(f"RF_{tag}1", f"[1][{hidden}]", zeros(hidden)), (f"RF_{tag}1_B", f"[{hidden}]", zeros(hidden)), (f"RF_{tag}2", f"[{hidden}]", zeros(hidden))]
    else:
        for tag, h in [("E", "head_e"), ("A", "head_a")]:
            arrays += [
                (f"RF_{tag}1", f"[{n_in}][{hidden}]", w[f"{h}.0.weight"].T), (f"RF_{tag}1_B", f"[{hidden}]", w[f"{h}.0.bias"]),
                (f"RF_{tag}2", f"[{hidden}]", w[f"{h}.2.weight"][0]),
            ]
        arrays += [("RF_S1", f"[1][{hidden}]", zeros(hidden)), ("RF_S1_B", f"[{hidden}]", zeros(hidden)), ("RF_S2", f"[2][{hidden}]", zeros(2, hidden)), ("RF_S2_B", "[2]", zeros(2))]
    lines = [
        f"// Generated by ml/rf_export.py from data/ml/{name}.pt. Do not edit.",
        f"constexpr int RF_UNIT = {n_unit}, RF_MEM = {n_mem}, RF_GAME = {n_game}, RF_W = {width}, RF_H = {hidden};",
    ]
    lines += [f"alignas(16) constexpr float {name}{shape} = {fmt(a)};" for name, shape, a in arrays]
    e_b, a_b = (0.0, 0.0) if shared else (float(w["head_e.2.bias"][0]), float(w["head_a.2.bias"][0]))
    lines.append(f"constexpr bool RF_SHARED = {'true' if shared else 'false'};")
    lines.append(f"constexpr float RF_E2_B = {lit(e_b)}, RF_A2_B = {lit(a_b)};")
    path = ROOT / "bots" / bot / "src" / "rf_weights.h"
    path.write_text("\n".join(lines) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
