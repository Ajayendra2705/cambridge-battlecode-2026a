import sys

import torch

from common import OUT, ROOT
from export_weights import fmt


def main():
    bot = sys.argv[1]
    ckpt = torch.load(OUT / "fpr_mlp.pt", weights_only=False)
    w = {k: v.cpu().numpy() for k, v in ckpt["state"].items()}
    s = ckpt["stats"]
    hidden, n_game = w["game.weight"].shape
    n_self = w["me.weight"].shape[1]
    arrays = [
        ("FPR_SELF_MEAN", f"[{n_self}]", s["unit"][0]), ("FPR_SELF_STD", f"[{n_self}]", s["unit"][1]),
        ("FPR_GAME_MEAN", f"[{n_game}]", s["game"][0]), ("FPR_GAME_STD", f"[{n_game}]", s["game"][1]),
        ("FPR_GAME_W", f"[{n_game}][{hidden}]", w["game.weight"].T), ("FPR_GAME_B", f"[{hidden}]", w["game.bias"]),
        ("FPR_SELF_W", f"[{n_self}][{hidden}]", w["me.weight"].T), ("FPR_TYPE", f"[13][{hidden}]", w["ty.weight"]),
        ("FPR_OUT_W", f"[2][{hidden}]", w["out.weight"]), ("FPR_OUT_B", "[2]", w["out.bias"]),
    ]
    lines = ["// Generated by ml/fpr_export.py from data/ml/fpr_mlp.pt. Do not edit.",
             f"constexpr int FPR_SELF = {n_self}, FPR_GAME = {n_game}, FPR_H = {hidden};"]
    lines += [f"alignas(16) constexpr float {n}{sh} = {fmt(a)};" for n, sh, a in arrays]
    path = ROOT / "bots" / bot / "src" / "fpr_weights.h"
    path.write_text("\n".join(lines) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
