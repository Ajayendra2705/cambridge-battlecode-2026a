import sys

import numpy as np
import torch

from common import OUT, ROOT


def arr(name, a):
    a = np.asarray(a, np.float32)
    dims = "".join(f"[{n}]" for n in a.shape)
    body = ", ".join(f"{v:.8g}f" for v in a.ravel())
    return f"constexpr float {name}{dims} = {{{body}}};\n" if a.ndim == 1 else \
        f"constexpr float {name}{dims} = {{{', '.join('{' + ', '.join(f'{v:.8g}f' for v in row) + '}' for row in a.reshape(a.shape[0], -1))}}};\n"


def main():
    dest = sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "ml/bot/eg_weights.h")
    ck = torch.load(OUT / "eg_poisson.pt", weights_only=False)
    s, w = ck["stats"], {k: v.cpu().numpy() for k, v in ck["state"].items()}
    assert s["mode"] == "poisson"
    out = ["// Generated by ml/eg_export.py from data/ml/eg_poisson.pt. Features: " + ", ".join(ck["features"]) + "\n",
           "#pragma once\n", f"constexpr int EG_N = {w['x.weight'].shape[1]}, EG_H = {w['x.weight'].shape[0]};\n",
           arr("EG_MEAN", s["mean"]), arr("EG_STD", s["std"]), arr("EG_W", w["x.weight"]), arr("EG_B", w["x.bias"]),
           arr("EG_TYPE", w["ty.weight"]), arr("EG_OUT_W", w["out.weight"]), arr("EG_OUT_B", w["out.bias"])]
    open(dest, "w").write("".join(out))
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
